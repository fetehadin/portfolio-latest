import {
  answeredFaqs,
  certificates,
  education,
  experience,
  formatMonth,
  moreProjects,
  practice,
  profile,
  projects,
  skills,
  socials,
} from "@/content/site";

const roleLines = () =>
  experience.flatMap((role) => [
    `### ${role.title}, ${role.org}`,
    "",
    `${formatMonth(role.from)} – ${formatMonth(role.to)} · ${role.location} · ${role.kind}`,
    "",
    role.summary,
    "",
    ...role.bullets.map((bullet) => `- ${bullet}`),
    "",
  ]);

/** The CV as Markdown, generated from content/site.ts. */
export function cvMarkdown() {
  return [
    `# ${profile.name}`,
    "",
    `${profile.role} · ${profile.city}, ${profile.country} (${profile.utc}) · ${profile.availability}`,
    "",
    `${profile.email} · ${profile.site}`,
    "",
    socials.map((s) => `[${s.network} ${s.handle}](${s.href})`).join(" · "),
    "",
    profile.positioning,
    "",
    profile.intro,
    "",
    "## Selected work",
    "",
    ...projects.flatMap((p) => [
      `### ${p.name}`,
      "",
      `${p.outcome}`,
      "",
      `${p.year} · ${p.role} · ${p.stack.join(", ")}`,
      "",
      p.links.length ? p.links.map((l) => `[${l.label}](${l.href})`).join(" · ") : `_${p.linkNote}_`,
      "",
      `Case study: ${profile.site}/work/${p.slug}`,
      "",
    ]),
    `More on GitHub: ${moreProjects.map((l) => `[${l.label}](${l.href})`).join(", ")}`,
    "",
    "## Experience",
    "",
    ...roleLines(),
    "## Skills",
    "",
    ...skills.map(({ group, items }) => `- **${group}:** ${items.join(", ")}`),
    `- **Practice:** ${practice.join(", ")}`,
    "",
    "## Education",
    "",
    ...education.map((e) => `- **${e.name}**, ${e.degree} (${e.start} – ${e.end})`),
    "",
    "## Certificates",
    "",
    ...certificates.map((c) => `- ${c.name} · ${c.issuer} · ${c.year}`),
    "",
  ].join("\n");
}

/** A plain-text summary for AI assistants, in the llms.txt format. */
export function llmsText() {
  return [
    `# ${profile.name}`,
    "",
    `> ${profile.role} in ${profile.city}, ${profile.country} (${profile.utc}). ${profile.positioning}`,
    "",
    `${profile.availability}. ${profile.contactLine} Email is the best way to reach me.`,
    "",
    `- Website: ${profile.site}`,
    `- Email: ${profile.email}`,
    ...socials.map((s) => `- ${s.network}: ${s.href}`),
    `- CV (Markdown): ${profile.site}/cv.md`,
    "",
    "## Case studies",
    "",
    ...projects.map((p) => `- [${p.name}](${profile.site}/work/${p.slug}): ${p.outcome}`),
    "",
    "## Experience",
    "",
    ...experience.map(
      (r) => `- ${r.org}, ${r.title} (${formatMonth(r.from)} – ${formatMonth(r.to)}): ${r.summary}`,
    ),
    "",
    "## Skills",
    "",
    ...skills.map(({ group, items }) => `- ${group}: ${items.join(", ")}`),
    "",
    "## FAQ",
    "",
    ...answeredFaqs.flatMap((f) => [`- ${f.q} ${f.a}`]),
    "",
  ].join("\n");
}
